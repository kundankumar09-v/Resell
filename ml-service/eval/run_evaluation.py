"""
ReSell ML evaluation harness (SYNTHETIC DATA).

Runs the fraud pipeline v1 (legacy hand-weighted scorer,
services/fraud_detector.py) and v2 (LightGBM + calibration,
pipeline/fraud_v2.py) on a labeled SYNTHETIC test dataset generated by
training/generate_synthetic_dataset.py, then computes:

  Fraud: accuracy, precision, recall, F1, AUC-ROC, confusion matrix
         (at each pipeline's operating threshold, plus a max-F1 threshold
         diagnostic that is threshold-independent)
  Price: MAE and MAPE of the price estimators (v1 kNN heuristic and v2
         quantile + conformal) against actual sold prices

Results are written as a markdown report to eval/RESULTS.md.

IMPORTANT: the dataset is SYNTHETIC - see the Limitations section of
eval/RESULTS.md. These numbers are NOT evidence of real-world performance.

Usage:
    python eval/run_evaluation.py
    python eval/run_evaluation.py --n-fraud 200 --n-legit 200 --seed 7
"""

