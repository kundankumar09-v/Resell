# 
# Evaluation loops
# 

def eval_fraud_v1(records) -> dict:
    """Run the legacy rule-based fraud pipeline; returns 0-1 scores + latency."""
    scores, lat = [], []
    for rec in records:
        t0 = time.perf_counter()
        res = v1_fraud(listing=rec["listing"], candidate_listings=rec["candidateListings"],
                       image_title_similarity=rec.get("imageTitleSimilarity"),
                       category_median_price=rec.get("categoryMedianPrice"))
        lat.append((time.perf_counter() - t0) * 1000)
        scores.append(float(res["fraudScore"]) / 100.0)
    return {"scores": np.array(scores), "latency": lat,
            "threshold": 0.70}  # v1 flags at fraudScore >= 70


def eval_fraud_v2(records) -> dict:
    """Run the v2 fraud pipeline (saved artifacts, or rule fallback if none)."""
    scores, lat, no_dup, reasons_log = [], [], 0, []
    thresholds = fv2.load_thresholds()
    for rec in records:
        t0 = time.perf_counter()
        res = fv2.evaluate_fraud_risk_v2(
            listing=rec["listing"], candidate_listings=rec["candidateListings"],
            category_median_price=rec.get("categoryMedianPrice"),
            image_title_similarity=rec.get("imageTitleSimilarity"))
        lat.append((time.perf_counter() - t0) * 1000)
        scores.append(float(res["fraudProbability"]))
    return {"scores": np.array(scores), "latency": lat,
            "threshold": float(thresholds.get("flag_threshold", 0.60)),
            "model_available": fv2.classifier.is_available()}


def eval_price_v1(records, k=5) -> dict:
    """Run the legacy kNN price estimator against sold prices."""
    preds, lat = [], []
    for rec in records:
        t0 = time.perf_counter()
        res = v1_price(target_embedding=rec.get("embedding"), target_metadata=rec,
                       comparables=rec.get("comparables") or [], k_neighbors=k)
        lat.append((time.perf_counter() - t0) * 1000)
        preds.append(float(res["suggestedPrice"]))
    return {"preds": np.array(preds), "latency": lat}


def eval_price_v2(records, k=12) -> dict:
    """Run the v2 quantile + conformal price pipeline against sold prices."""
    preds, lat, no_sugg = [], [], 0
    for rec in records:
        t0 = time.perf_counter()
        res = pv2.evaluate_price_v2(rec, rec.get("comparables") or [],
                                    target_embedding=rec.get("embedding"), k_neighbors=k)
        lat.append((time.perf_counter() - t0) * 1000)
        sp = res.get("suggestedPrice")
        if sp is None:
            no_sugg += 1
            sp = np.nan
        preds.append(float(sp))
    return {"preds": np.array(preds), "latency": lat,
            "no_suggestion": no_sugg,
            "model_available": pv2.model_v2.is_available()}


# 
# Metrics
# 

def fraud_metrics(y_true: np.ndarray, scores: np.ndarray, threshold: float) -> dict:
    """Accuracy / precision / recall / F1 / AUC-ROC / confusion matrix at a threshold."""
    y = np.asarray(y_true, dtype=np.int32)
    s = np.asarray(scores, dtype=np.float64)
    preds = (s >= threshold).astype(np.int32)

    tn, fp, fn, tp = confusion_matrix(y, preds, labels=[0, 1]).ravel()
    # Max-F1 threshold diagnostic (threshold-independent reference point)
    max_f1_thr = None
    if len(np.unique(y)) > 1 and len(np.unique(s)) > 1:
        prec, rec, thr = precision_recall_curve(y, s)
        f1 = 2 * prec[:-1] * rec[:-1] / np.maximum(prec[:-1] + rec[:-1], 1e-9)
        max_f1_thr = float(thr[int(np.argmax(f1))]) if len(thr) else None

    return {
        "threshold": round(float(threshold), 4),
        "accuracy": round(float(accuracy_score(y, preds)), 4),
        "precision": round(float(precision_score(y, preds, zero_division=0)), 4),
        "recall": round(float(recall_score(y, preds, zero_division=0)), 4),
        "f1": round(float(f1_score(y, preds, zero_division=0)), 4),
        "auc_roc": round(float(roc_auc_score(y, s)), 4) if len(np.unique(y)) > 1 else None,
        "confusion": {"tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp)},
        "max_f1_threshold": round(max_f1_thr, 4) if max_f1_thr is not None else None,
    }


def price_metrics(y_true: np.ndarray, preds: np.ndarray) -> dict:
    """MAE and MAPE of the price estimator against actual sold prices."""
    y = np.asarray(y_true, dtype=np.float64)
    p = np.asarray(preds, dtype=np.float64)
    mask = (y > 0) & np.isfinite(p) & (p > 0)
    y, p = y[mask], p[mask]
    if len(y) == 0:
        return {"mae": None, "mape_pct": None, "n_scored": 0}
    return {
        "mae": round(float(np.mean(np.abs(p - y))), 2),
        "mape_pct": round(float(np.mean(np.abs(p - y) / y) * 100.0), 2),
        "n_scored": int(len(y)),
    }


