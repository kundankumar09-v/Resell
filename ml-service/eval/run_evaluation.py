def build_report(results: dict) -> str:
    lines = []
    a = lines.append
    a("# ReSell ML Evaluation Results")
    a("")
    a(f"_Generated: {time.strftime('%Y-%m-%d %H:%M:%S')} - "
      f"harness: `ml-service/eval/run_evaluation.py`_")
    a("")
    a("> **DATA IS SYNTHETIC.** Every sample in this evaluation was generated by "
      "`ml-service/training/generate_synthetic_dataset.py`. No real marketplace "
      "listings were used. These numbers measure pipeline behaviour on simulated "
      "distributions only - real-world performance is unvalidated.")
    a("")

    d = results["dataset"]
    a("## Dataset (synthetic)")
    a("")
    a(f"- Sample size: **{d['n_samples']} labeled fraud-detection samples** "
      f"({d['n_fraud']} fraud / {d['n_legit']} legitimate) + **{d['n_price']} "
      f"sold listings** for price-estimator scoring")
    a(f"- Generator: `training/generate_synthetic_dataset.py` (seed {d['seed']}), "
      f"class-balanced by construction")
    a(f"- Fraud sub-cases: {json.dumps(d['cases'], sort_keys=True)}")
    a("- Feature distributions mirror the 14 engineered features in "
      "`pipeline/fraud_v2.py`: duplicate pHash pairs (Hamming distance 0-4), "
      "price outliers (z-score -3 to -9), new accounts (<48h) with burst listing "
      "rates (8-30/hour), stock photo dimensions (1920x1080 / 1200x800 / "
      "1000x1000), suspicious software tags; legitimate samples use realistic "
      "phone/camera dimensions, mature accounts, in-band prices and "
      "same-seller relists (labeled legit, per v2 semantics).")
    a("")
    a("## Pipelines under test")
    a("")
    a("| Task | Version | Available | Operating threshold |")
    a("|---|---|---|---|")
    f1m = results["fraud_v1"]
    f2m = results["fraud_v2"]
    a(f"| Fraud detection | v1 (legacy rules) | {f1m.get('available')} | "
      f"{f1m.get('threshold')} (fraudScore >= 70 on 0-100 scale) |")
    a(f"| Fraud detection | v2 (LightGBM + calibration) | {f2m.get('available')} | "
      f"{f2m.get('threshold')} (flag_threshold from "
      f"`models_saved/fraud_v2_thresholds.json`) |")
    p1m = results["price_v1"]
    p2m = results["price_v2"]
    a(f"| Price estimation | v1 (kNN heuristic) | {p1m.get('available')} | - |")
    a(f"| Price estimation | v2 (quantile + conformal) | {p2m.get('available')} | - |")
    a("")

    a("## Fraud detection metrics (at operating threshold)")
    a("")
    a("| Metric | v1 (legacy) | v2 (upgrade) | Delta |")
    a("|---|---|---|---|")
    for key, label in [("accuracy", "Accuracy"), ("precision", "Precision"),
                       ("recall", "Recall"), ("f1", "F1"), ("auc_roc", "AUC-ROC")]:
        b, v = f1m.get(key), f2m.get(key)
        delta = (v - b) if (b is not None and v is not None) else None
        delta_s = f"{delta*100:+.2f}pp" if delta is not None else "-"
        a(f"| {label} | {b if b is not None else '-'} | {v if v is not None else '-'} | {delta_s} |")
    a("")
    a("### Confusion matrix (threshold = flag threshold)")
    a("")
    a("| | Predicted legit | Predicted fraud |")
    a("|---|---|---|")
    cb, cv = f1m["confusion"], f2m["confusion"]
    a(f"| **Actual legit** (v1 / v2) | TN: {cb['tn']} / {cv['tn']} | FP: {cb['fp']} / {cv['fp']} |")
    a(f"| **Actual fraud** (v1 / v2) | FN: {cb['fn']} / {cv['fn']} | TP: {cb['tp']} / {cv['tp']} |")
    a("")
    a("### Max-F1 threshold diagnostic")
    a("")
    a(f"- v1: best F1 at threshold `{f1m.get('max_f1_threshold')}` "
      f"(operating point uses 0.70)")
    a(f"- v2: best F1 at threshold `{f2m.get('max_f1_threshold')}` "
      f"(operating point uses the persisted flag threshold {f2m.get('threshold')})")
    a("")
    a("### Latency (per call, ms)")
    a("")
    a("| Pipeline | p50 | p95 | mean |")
    a("|---|---|---|---|")
    for name, res in [("Fraud v1", f1m), ("Fraud v2", f2m),
                      ("Price v1", p1m), ("Price v2", p2m)]:
        lat = res.get("latency") or {}
        if lat.get("p50_ms") is None:
            continue
        a(f"| {name} | {lat['p50_ms']} | {lat['p95_ms']} | {lat['mean_ms']} |")
    a("")

    a("## Price estimation metrics (against actual sold prices)")
    a("")
    a("| Metric | v1 (kNN heuristic) | v2 (quantile + conformal) |")
    a("|---|---|---|")
    a(f"| MAE ($) | {p1m.get('mae')} | {p2m.get('mae')} |")
    a(f"| MAPE | {p1m.get('mape_pct')}% | {p2m.get('mape_pct')}% |")
    a(f"| No-suggestion rate | 0% | "
      f"{round(100.0 * p2m.get('no_suggestion', 0) / max(1, d['n_price']), 1)}% |")
    a(f"| Listings scored | {p1m.get('n_scored')} | {p2m.get('n_scored')} |")
    a("")

    a("## Limitations")
    a("")
    a("- **The data is entirely synthetic.** It was generated by "
      "`training/generate_synthetic_dataset.py` from hand-chosen distributions, "
      "not sampled from real ReSell traffic. Real-world performance is "
      "**unvalidated**; these results must not be used as production evidence.")
    a("- The generator encodes the same signal definitions the pipelines "
      "detect (pHash bit flips, embedding-copy noise, z-score price cuts), so "
      "fraud metrics are optimistic: the pipelines were largely designed "
      "against exactly these patterns, and the v2 artifacts in "
      "`models_saved/` were themselves trained on similarly generated data.")
    a("- There is no train/test split in this harness: the saved v2 model "
      "artifacts are scored on freshly generated (but distribution-identical) "
      "samples, so there is no distribution-shift signal either.")
    a("- Vision-LLM features (`vision_llm_flag_count`, "
      "`vision_llm_confidence`) are always 0 here (no NVIDIA API key, no "
      "images in the synthetic set), and CLIP image-text similarity is passed "
      "as a provided value rather than computed from real images.")
    a("- Price comparables and the ANN index are built from the same synthetic "
      "pool being scored, so price MAE/MAPE do not reflect the sparse, noisy "
      "comparable data seen in production.")
    a("- Sample sizes (200 fraud labels, 200 sold listings) are small; metric "
      "differences of a few points are within noise.")
    a("")

    return "\n".join(lines)


# 

def main():
    parser = argparse.ArgumentParser(description="ReSell ML evaluation harness (synthetic)")
    parser.add_argument("--n-fraud", type=int, default=100)
    parser.add_argument("--n-legit", type=int, default=100)
    parser.add_argument("--n-price", type=int, default=200)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    # (a) Load the labeled test dataset (generate + cache to disk if absent)
    if os.path.exists(DEFAULT_DATA_PATH):
        ds = load_dataset(DEFAULT_DATA_PATH)
        print(f"Loaded labeled SYNTHETIC dataset from {DEFAULT_DATA_PATH}")
    else:
        ds = generate_synthetic_dataset(n_fraud=args.n_fraud, n_legit=args.n_legit,
                                        n_price=args.n_price, seed=args.seed)
        save_dataset(ds)
        print(f"Generated SYNTHETIC dataset and saved to {DEFAULT_DATA_PATH}")

    fraud_records, price_records = ds["fraud"], ds["price"]
    n_pos = sum(1 for r in fraud_records if r["label"] == 1)
    n_neg = len(fraud_records) - n_pos
    cases = {}
    for r in fraud_records:
        key = f"{r['case']}(label={r['label']})"
        cases[key] = cases.get(key, 0) + 1
    print(f"  fraud: {len(fraud_records)} samples ({n_pos} fraud / {n_neg} legit)")
    print(f"  sub-cases: {json.dumps(cases, sort_keys=True)}")
    print(f"  price: {len(price_records)} sold listings")

    dataset_meta = {
        "n_samples": len(fraud_records),
        "n_fraud": n_pos,
        "n_legit": n_neg,
        "n_price": len(price_records),
        "seed": args.seed,
        "cases": cases,
    }
    results = {"dataset": dataset_meta}
    y_true = np.array([r["label"] for r in fraud_records], dtype=np.int32)

    # (b) Fraud pipelines, v1 and v2
    if V1_FRAUD_AVAILABLE:
        print("Evaluating fraud v1 (legacy rules)...")
        r1 = eval_fraud_v1(fraud_records)
        r1["metrics"] = fraud_metrics(y_true, r1["scores"], r1["threshold"])
        r1["available"] = True
    else:
        print(f"fraud v1 SKIPPED: {V1_FRAUD_IMPORT_ERROR}")
        r1 = {"available": False, "import_error": V1_FRAUD_IMPORT_ERROR}

    if V2_FRAUD_AVAILABLE:
        print("Evaluating fraud v2 (LightGBM + calibration)...")
        r2 = eval_fraud_v2(fraud_records)
        r2["metrics"] = fraud_metrics(y_true, r2["scores"], r2["threshold"])
        r2["available"] = True
    else:
        print(f"fraud v2 SKIPPED: {V2_FRAUD_IMPORT_ERROR}")
        r2 = {"available": False, "import_error": V2_FRAUD_IMPORT_ERROR}

    # (c) Price estimators against actual sold prices
    if V2_PRICE_AVAILABLE:
        print("Building ANN index for v2 price kNN features...")
        ann_index.build_global(price_records)

    if V1_PRICE_AVAILABLE:
        print("Evaluating price v1 (kNN heuristic)...")
        p1 = eval_price_v1(price_records)
        p1.update(price_metrics([r["soldPrice"] for r in price_records], p1["preds"]))
        p1["available"] = True
    else:
        print(f"price v1 SKIPPED: {V1_PRICE_IMPORT_ERROR}")
        p1 = {"available": False, "import_error": V1_PRICE_IMPORT_ERROR}

    if V2_PRICE_AVAILABLE:
        print("Evaluating price v2 (quantile + conformal)...")
        p2 = eval_price_v2(price_records)
        p2.update(price_metrics([r["soldPrice"] for r in price_records], p2["preds"]))
        p2["available"] = True
    else:
        print(f"price v2 SKIPPED: {V2_PRICE_IMPORT_ERROR}")
        p2 = {"available": False, "import_error": V2_PRICE_IMPORT_ERROR}

    # Latency percentiles for all four
    for name, res in [("fraud_v1", r1), ("fraud_v2", r2), ("price_v1", p1), ("price_v2", p2)]:
        lat = res.get("latency")
        if lat:
            a = np.array(lat, dtype=np.float64)
            res["latency"] = {"p50_ms": round(float(np.percentile(a, 50)), 2),
                              "p95_ms": round(float(np.percentile(a, 95)), 2),
                              "mean_ms": round(float(np.mean(a)), 2)}

    # Flatten metric dicts for the report builder
    for src, dst in [(r1, "fraud_v1"), (r2, "fraud_v2"), (p1, "price_v1"), (p2, "price_v2")]:
        entry = {k: v for k, v in src.items() if k not in ("scores", "preds", "metrics")}
        entry.update(src.get("metrics") or {})
        entry["latency"] = src.get("latency")
        results[dst] = entry

    # (e) Write the markdown report
    report = build_report(results)
    with open(RESULTS_PATH, "w", encoding="utf-8") as f:
        f.write(report)
    print(f"\nResults written to {RESULTS_PATH}")
    print(report)


if __name__ == "__main__":
    main()
